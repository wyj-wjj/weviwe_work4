def _txt(*parts: str) -> str:
    return "".join(parts)


def _lines(*parts: str) -> str:
    return "\n".join(part.strip() for part in parts if part and part.strip())


def _title(title: str) -> str:
    return f"{TITLE_PREFIX}{title}"


def _must_read(
    *,
    title: str,
    category: str,
    level: ContentLevel,
    summary: str,
    body_lines: list[str],
    points: list[str],
) -> ContentCreate:
    update_body = _lines(*body_lines)
    body = _lines(summary, body_lines[0])
    return ContentCreate(
        content_type=ContentType.MUST_READ,
        title=_title(title),
        category=category,
        permission_level=level,
        summary=summary,
        body=body,
        structured_payload={
            "update_body": update_body,
            "adjustment_points": points,
        },
    )


def _base_script(
    *,
    title: str,
    category: str,
    level: ContentLevel,
    summary: str,
    body: str,
    points: list[str],
) -> ContentCreate:
    return ContentCreate(
        content_type=ContentType.BASE_SCRIPT,
        title=_title(title),
        category=category,
        permission_level=level,
        summary=summary,
        body=body,
        structured_payload={"points": points},
    )


def _item(scene: str, recommended: str, forbidden: str, notes: str) -> dict[str, str]:
    return {
        "scene": scene,
        "recommended_speech": recommended,
        "forbidden_speech": forbidden,
        "notes": notes,
    }


def _standard_items(
    *,
    title: str,
    category: str,
    level: ContentLevel,
    summary: str,
    items: list[dict[str, str]],
) -> ContentCreate:
    scene_names = "；".join(item["scene"] for item in items)
    return ContentCreate(
        content_type=ContentType.STANDARD_SCRIPT,
        title=_title(title),
        category=category,
        permission_level=level,
        summary=summary,
        body=_lines(
            summary,
            f"本话术覆盖以下客户场景：{scene_names}。",
            "使用时应先复述客户问题，再给出官方口径，并明确需要后续确认的边界。",
        ),
        structured_payload={
            # Current ContentCreate schema requires a top-level scene even when
            # the RAG indexer uses items mode.
            "scene": "多场景合集",
            "recommended_speech": f"本条为多场景话术合集，覆盖：{scene_names}。",
            "forbidden_speech": "不得承诺未验证的参数、审批结果、收益水平或内部资源安排。",
            "notes": "items 字段用于验证标准话术多 chunk 召回和多来源合并。",
            "items": items,
        },
    )


def _standard_single(
    *,
    title: str,
    category: str,
    level: ContentLevel,
    summary: str,
    scene: str,
    recommended: str,
    forbidden: str,
    notes: str,
) -> ContentCreate:
    return ContentCreate(
        content_type=ContentType.STANDARD_SCRIPT,
        title=_title(title),
        category=category,
        permission_level=level,
        summary=summary,
        body=_lines(summary, scene, recommended),
        structured_payload={
            "scene": scene,
            "recommended_speech": recommended,
            "forbidden_speech": forbidden,
            "notes": notes,
        },
    )


