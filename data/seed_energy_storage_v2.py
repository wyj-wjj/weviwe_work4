def validate_seed_users(db: Session) -> User:
    users: dict[str, User] = {}
    for username, (expected_id, account_type, content_level) in EXPECTED_USERS.items():
        user = db.scalar(select(User).where(User.username == username))
        if user is None:
            raise SystemExit(f"ERROR: required seed user '{username}' does not exist.")
        if not user.is_active:
            raise SystemExit(f"ERROR: required seed user '{username}' is disabled.")
        if user.account_type != account_type or user.content_level != content_level:
            raise SystemExit(
                "ERROR: required seed user "
                f"'{username}' has unexpected role/level: {user.account_type}/{user.content_level}."
            )
        if user.id != expected_id:
            print(f"  warning: {username} id is {user.id}, expected {expected_id}; continuing by username.")
        users[username] = user
    return users["es_admin"]


def validate_payloads(payloads: Iterable[ContentCreate]) -> list[ContentCreate]:
    payload_list = list(payloads)
    titles = [payload.title for payload in payload_list]
    duplicate_titles = sorted({title for title in titles if titles.count(title) > 1})
    if duplicate_titles:
        raise SystemExit(f"ERROR: duplicate content titles in v2 payloads: {duplicate_titles}")
    if len(payload_list) != 52:
        raise SystemExit(f"ERROR: expected 52 content payloads, got {len(payload_list)}")
    return payload_list


def has_active_index_record(db: Session, *, content: Content, collection_name: str) -> bool:
    if content.current_version_id is None:
        return False
    count = db.scalar(
        select(func.count())
        .select_from(VectorIndexRecord)
        .where(VectorIndexRecord.content_id == content.id)
        .where(VectorIndexRecord.version_id == content.current_version_id)
        .where(VectorIndexRecord.milvus_collection == collection_name)
        .where(VectorIndexRecord.is_active.is_(True))
    )
    return bool(count)


def ensure_contents_v2(
    db: Session,
    *,
    admin: User,
    payloads: list[ContentCreate],
    settings: Settings,
    dashscope_client,
    milvus_client,
    resync_existing: bool,
) -> tuple[dict[str, Content], int, int, int, int]:
    content_by_title: dict[str, Content] = {}
    pending_sync_ids: list[int] = []
    created_count = 0
    skipped_count = 0

    print("\n[2/4] Creating and publishing v2 content ...")
    for payload in payloads:
        existing = db.scalar(select(Content).where(Content.title == payload.title))
        if existing is not None:
            skipped_count += 1
            content_by_title[payload.title] = existing
            if existing.status != ContentStatus.PUBLISHED.value or existing.current_version_id is None:
                print(f"  skip existing non-published content: {payload.title}")
                continue
            needs_sync = (
                resync_existing
                or existing.index_status != IndexStatus.SYNCED.value
                or not has_active_index_record(db, content=existing, collection_name=settings.milvus_collection_name)
            )
            if needs_sync:
                pending_sync_ids.append(existing.id)
                print(f"  queue sync existing: {payload.title}")
            else:
                print(f"  skip existing synced: {payload.title}")
            continue

        content = create_content(db, creator=admin, payload=payload)
        publish_content(db, content_id=content.id)
        content = db.get(Content, content.id)
        if content is None:
            raise SystemExit(f"ERROR: content disappeared after publish: {payload.title}")
        db.refresh(content)
        content_by_title[payload.title] = content
        pending_sync_ids.append(content.id)
        created_count += 1
        print(f"  created+published [{content.permission_level}/{content.content_type}]: {payload.title}")

    print(f"\n[3/4] Syncing v2 vectors to Milvus collection '{settings.milvus_collection_name}' ...")
    synced_count = 0
    sync_failed_count = 0
    for content_id in pending_sync_ids:
        content = db.get(Content, content_id)
        if content is None:
            sync_failed_count += 1
            print(f"  failed: content id {content_id} not found")
            continue
        result = sync_content_index(
            db,
            content_id=content.id,
            dashscope_client=dashscope_client,
            milvus_client=milvus_client,
            settings=settings,
        )
        if result.status == IndexStatus.SYNCED.value:
            synced_count += 1
            print(f"  synced [{result.indexed_count} vectors]: {content.title}")
        else:
            sync_failed_count += 1
            print(f"  sync failed [{result.error_code}]: {content.title}")

    for payload in payloads:
        refreshed = db.scalar(select(Content).where(Content.title == payload.title))
        if refreshed is not None:
            content_by_title[payload.title] = refreshed

    return content_by_title, created_count, skipped_count, synced_count, sync_failed_count


def dedupe_active_vector_records_v2(db: Session, *, collection_name: str) -> int:
    """Keep one active VectorIndexRecord per active v2 chunk in the current collection."""
    records = db.scalars(
        select(VectorIndexRecord)
        .join(Content, Content.id == VectorIndexRecord.content_id)
        .where(Content.title.like(f"{TITLE_PREFIX}%"))
        .where(VectorIndexRecord.milvus_collection == collection_name)
        .where(VectorIndexRecord.is_active.is_(True))
        .order_by(VectorIndexRecord.chunk_id.asc(), VectorIndexRecord.id.desc())
    ).all()

    seen_chunk_ids: set[int] = set()
    deduped = 0
    for record in records:
        if record.chunk_id in seen_chunk_ids:
            record.is_active = False
            deduped += 1
            continue
        seen_chunk_ids.add(record.chunk_id)
    if deduped:
        db.commit()
    return deduped


def ensure_quiz_questions_v2(db: Session, *, content_by_title: dict[str, Content]) -> tuple[int, int]:
    created_count = 0
    skipped_count = 0
    print("\n[4/4] Creating v2 quiz questions ...")
    for spec in quiz_question_specs():
        existing = db.scalar(select(QuizQuestion).where(QuizQuestion.question == spec["question"]))
        if existing is not None:
            skipped_count += 1
            print(f"  skip quiz: {spec['question']}")
            continue

        related_title = _title(spec["related_title"])
        related_content = content_by_title.get(related_title)
        if related_content is None:
            related_content = db.scalar(select(Content).where(Content.title == related_title))
        if related_content is None:
            raise SystemExit(f"ERROR: related content not found for quiz: {related_title}")

        db.add(
            QuizQuestion(
                question=spec["question"],
                options=spec["options"],
                answer=spec["answer"],
                explanation=spec["explanation"],
                related_content_id=related_content.id,
                permission_level=spec["permission_level"].value,
                status=QuestionStatus.ENABLED.value,
            )
        )
        created_count += 1
        print(f"  created quiz [{spec['permission_level'].value}]: {spec['question']}")
    return created_count, skipped_count


def print_existing_summary(db: Session) -> None:
    v2_content_count = db.scalar(select(func.count()).select_from(Content).where(Content.title.like(f"{TITLE_PREFIX}%"))) or 0
    v2_quiz_count = db.scalar(select(func.count()).select_from(QuizQuestion).where(QuizQuestion.question.like(f"{TITLE_PREFIX}%"))) or 0
    v2_vector_count = (
        db.scalar(
            select(func.count())
            .select_from(VectorIndexRecord)
            .join(Content, Content.id == VectorIndexRecord.content_id)
            .where(Content.title.like(f"{TITLE_PREFIX}%"))
            .where(VectorIndexRecord.is_active.is_(True))
        )
        or 0
    )
    print(f"  existing v2 contents: {v2_content_count}")
    print(f"  existing v2 quiz questions: {v2_quiz_count}")
    print(f"  existing active v2 vector records: {v2_vector_count}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Seed v2 energy-storage content into MySQL and Milvus.")
